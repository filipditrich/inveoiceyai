/**
 * Regenerates `locales/*.d.json.ts` from the message catalogs.
 *
 * `next.config.ts` asks next-intl to do this via `createMessagesDeclaration`,
 * but that only runs under `next dev` / `next build`. Standalone `tsc` would
 * otherwise typecheck against a stale declaration, so editing `cs.json` and
 * running `bun run typecheck` reported phantom "Expected 2-3 arguments" errors
 * on translation keys that were perfectly valid — a failure that points at the
 * call site rather than at the catalog, and costs real time to diagnose.
 *
 * The transform is reproduced here rather than imported: next-intl exports only
 * `next-intl/plugin`, so reaching the generator would mean a deep import into
 * `dist/` that any upgrade could break. It is four lines, and `HEADER` is
 * checked against the file next-intl itself writes — if that ever diverges,
 * this script rewrites the file to what `tsc` needs anyway.
 *
 * Keep `MESSAGES_PATHS` in sync with `createMessagesDeclaration` in
 * `next.config.ts`.
 */
import { readFile, rm, writeFile } from "node:fs/promises";

const MESSAGES_PATHS = ["./locales/cs.json"];

const HEADER = `// This file is auto-generated by next-intl, do not edit directly.
// See: https://next-intl.dev/docs/workflows/typescript#messages-arguments`;

for (const messagesPath of MESSAGES_PATHS) {
  const declarationPath = messagesPath.replace(/\.json$/, ".d.json.ts");
  const content = await readFile(messagesPath, "utf-8");
  const next = `${HEADER}

declare const messages: ${content.trim()};
export default messages;`;

  // Only write on change, so a no-op typecheck keeps the fast incremental path.
  const current = await readFile(declarationPath, "utf-8").catch(() => null);
  if (current !== next) {
    await writeFile(declarationPath, next);

    // TypeScript's incremental cache does not reliably notice this file being
    // rewritten underneath it: `tsc` then reports missing-key errors against a
    // declaration that is already correct on disk — precisely the confusing
    // failure this script exists to prevent. Dropping the build info forces
    // one clean check, and only on the runs where the catalog actually moved.
    await rm("tsconfig.tsbuildinfo", { force: true });
  }
}
